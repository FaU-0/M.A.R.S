def make_holdout(seed=77, n=10):
    return make(seed, n, HOLDOUT)


def make(seed=2026, n=20, pools=None):
    P = dict(PATIENTS=PATIENTS, DOCTORS=DOCTORS, RELATIVES=RELATIVES, CITIES=CITIES, ORGS=ORGS, SCHOOLS=SCHOOLS)
    P.update(pools or {})
    rng = random.Random(seed)
    out = []
    for i in range(n):
        full, call, sur = P["PATIENTS"][i % len(P["PATIENTS"])]
        doc = P["DOCTORS"][i % len(P["DOCTORS"])]
        dfirst = " ".join(doc.split()[1:])
        compl, ck = rng.choice(COMPLAINTS)
        drug, dt = rng.choice(DRUGS)
        rel = rng.sample(P["RELATIVES"], 2)
        city = rng.choice(P["CITIES"])
        org = rng.choice(P["ORGS"])
        school = rng.choice(P["SCHOOLS"])
        st = rng.sample(STRUCT, 3)
        pii = [(call, "entity"), (sur, "entity"), (rel[0][0].split(" ", 1)[1], "entity"), (rel[1][0].split(" ", 1)[1], "entity"),
               (city[0].split(" ", 1)[1], "entity"), (org[0].split(" ", 1)[1], "entity"), (school[0].split(" ", 1)[1], "entity"),
               (dfirst, "entity")] + [(x, "structured") for x, _ in st]
        lines = [
            ("doctor", "Здравствуйте, %s. Я %s, ваш врач. Что вас беспокоит?" % (call, dfirst)),
            ("patient", "Здравствуйте, доктор. У меня %s." % compl),
            ("doctor", "Понятно. Как давно это началось? Вы что-нибудь принимали?"),
            ("patient", "Дня четыре назад. %s." % cap(dt.format(d=drug))),
            ("patient", cap(rel[0][1].format(r=rel[0][0])) + ", и " + city[1].format(c=city[0]) + "."),
            ("doctor", "Хорошо. Где вы работаете или учитесь?"),
            ("patient", cap(org[1].format(o=org[0])) + ". А " + school[1].format(s=school[0]) + "."),
            ("doctor", "Для карты уточню: фамилия %s, верно? Продиктуйте данные." % sur),
            ("patient", "Да. " + cap(st[0][1].format(x=st[0][0])) + ", " + st[1][1].format(x=st[1][0]) + "."),
            ("patient", cap(st[2][1].format(x=st[2][0])) + ". " + cap(rel[1][1].format(r=rel[1][0])) + "."),
            ("doctor", "Спасибо. Продолжайте принимать %s, если нет аллергии, и сдайте общий анализ крови. Если станет хуже, вызывайте скорую." % drug),
        ]
        segs = [{"role": r, "t": k * 7000, "text": t} for k, (r, t) in enumerate(lines)]
        known = {"patient": {"full_name": full}, "doctor": {"name": doc}}
        out.append({"segments": segs, "known": known, "pii": pii, "keep": ck + [drug, "анализ крови"]})
    return out


